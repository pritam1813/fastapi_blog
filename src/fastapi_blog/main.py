@app.post(
    "/api/users", response_model=UserResponse, status_code=status.HTTP_201_CREATED
)  # db: is dependency Injection
def create_user(user: UserCreate, db: Annotated[Session, Depends(get_db)]):
    result = db.execute(
        select(models.User).where(models.User.username == user.username)
    )
    existing_user = result.scalars().first()

    if existing_user:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Username already exists",
        )

    result = db.execute(select(models.User).where(models.User.email == user.email))
    existing_email = result.scalars().first()

    if existing_email:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Email already exists",
        )

    new_user = models.User(username=user.username, email=user.email)

    db.add(new_user)
    db.commit()
    db.refresh(new_user)

    return new_user


@app.patch("/api/users/{user_id}", response_model=UserResponse)
def update_user(
    user_id: int, user_details: UserUpdate, db: Annotated[Session, Depends(get_db)]
):
    result = db.execute(select(models.User).where(models.User.id == user_id))
    user = result.scalars().first()

    if not user:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND, detail="User not found"
        )

    if user_details.username is not None and user_details.username != user.username:
        result = db.execute(
            select(models.User).where(models.User.username == user_details.username)
        )
        existing_user = result.scalars().first()

        if existing_user:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="Username already exists",
            )

    if user_details.email is not None and user_details.email != user.email:
        result = db.execute(
            select(models.User).where(models.User.email == user_details.email)
        )
        existing_user = result.scalars().first()

        if existing_user:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="Email already registered.",
            )

    if user_details.username is not None:
        user.username = user_details.username
    if user_details.email is not None:
        user.email = user_details.email
    if user_details.image_file is not None:
        user.image_file = user_details.image_file

    db.commit()
    db.refresh(user)
    return user


